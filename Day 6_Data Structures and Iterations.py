# Day 6: Data Structures & Iterations
# ==========================================

# 1. Tuple (Immutable Data)
box_dimensions = (10, 20, 30)
print(box_dimensions[0])

# 2. Dictionary (Key-Value Pairs)
user_profile = {"username": "bhavani_coder", "email": "bhavani@email.com"}
print(user_profile["username"])

# 3. Set (Unique Values Only)
employee_ids = {101, 102, 101, 103}
print(employee_ids)

# 4. While Loop (Iteration)
countdown = 3
while countdown > 0:
    print(countdown)
    countdown -= 1

# 5. String Formatting
language = "Java"
print("you love", language)
